/** 12×12 그림 + 1칸 여백 + 오른쪽 아래 표시 → 14×14 캔버스 */
export function paintCard(id: string, scale: number): HTMLCanvasElement | null {
  const art = CARD_ART[id];
  if (!art) return null;
  const pal = art.pal ?? PAL;
  const N = 14;
  const c = document.createElement("canvas");
  c.width = N * scale;
  c.height = N * scale;
  const ctx = c.getContext("2d")!;
  const h = art.rows.length;
  const w = Math.max(...art.rows.map((r) => r.length));
  const ox = 1 + Math.floor((12 - w) / 2);
  const oy = 1 + Math.floor((12 - h) / 2);
  art.rows.forEach((row, y) => {
    [...row].forEach((ch, x) => {
      const col = pal[ch];
      if (!col) return;
      ctx.fillStyle = col;
      ctx.fillRect((ox + x) * scale, (oy + y) * scale, scale, scale);
    });
  });
  if (art.badge) {
    const b = BADGES[art.badge];
    const bx = 9, by = 9;
    // 어두운 테두리 먼저
    ctx.fillStyle = "#0b0a0f";
    b.rows.forEach((row, y) => [...row].forEach((ch, x) => {
      if (ch !== "x") return;
      for (const [dx, dy] of [[-1, 0], [1, 0], [0, -1], [0, 1]]) ctx.fillRect((bx + x + dx) * scale, (by + y + dy) * scale, scale, scale);
    }));
    ctx.fillStyle = b.color;
    b.rows.forEach((row, y) => [...row].forEach((ch, x) => {
      if (ch === "x") ctx.fillRect((bx + x) * scale, (by + y) * scale, scale, scale);
    }));
  }
  return c;
}
